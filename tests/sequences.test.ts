const empty = catalog([]);

test("numbered grows past the pad", () => {
  expect(numbered("number", { prefix: "INV-", pad: 6 }).text).toBe(
    `'INV-' || lpad("number"::text, greatest(6, length("number"::text)), '0')`,
  );
});

test("identity refuses scope, reset, and when", () => {
  expect(() => t.identity({ scope: ["tenantId"] } as never)).toThrow(OkmError);
  try {
    t.identity({ reset: "year" } as never);
  } catch (error) {
    expect(error).toBeInstanceOf(OkmError);
    expect((error as OkmError).code).toBe("OKM1060");
    expect((error as OkmError).message).toContain("sequence() from okmodel/seq");
  }
});

test("a native sequence is created before the table and owned by the column", () => {
  const built = schema({
    tables: [table("docs", { number: sequence({ start: 10, increment: 2 }).column() })],
  });
  const plan = planMigration({ before: empty, after: built.catalog, name: "native" });
  const sql = plan.steps.map((step) => step.sql);
  const sequenceAt = sql.findIndex((item) => item.startsWith("create sequence"));
  const tableAt = sql.findIndex((item) => item.startsWith("create table"));
  expect(sequenceAt).toBeGreaterThanOrEqual(0);
  expect(tableAt).toBeGreaterThan(sequenceAt);
  expect(sql.some((item) => item.includes("owned by"))).toBe(true);
  expect(sql.join("\n")).toContain("start 10");
  expect(sql.join("\n")).toContain("increment 2");
});

test("identity options are on the column and not a separate create sequence", () => {
  const built = schema({
    tables: [
      table("docs", {
        id: t.identity({ generated: "byDefault", start: 5, cache: 20 }),
      }),
    ],
  });
  const plan = planMigration({ before: empty, after: built.catalog, name: "identity" });
  const text = plan.steps.map((step) => step.sql).join("\n");
  expect(text).toContain("generated by default as identity");
  expect(text).toContain("start with 5");
  expect(text).toContain("cache 20");
  expect(text).not.toContain("create sequence");
});

test("a changed start is a warning and does not restart", () => {
  const before = schema({
    tables: [table("docs", { number: sequence({ start: 1 }).column() })],
  }).catalog;
  const after = schema({
    tables: [table("docs", { number: sequence({ start: 9 }).column() })],
  }).catalog;
  const plan = planMigration({ before, after, name: "start" });
  expect(plan.steps.map((step) => step.sql).join("\n")).not.toContain("restart");
  expect(plan.warnings?.some((item) => item.code === "OKM2120")).toBe(true);
});

test("min above max is refused", () => {
  const after = schema({
    tables: [table("docs", { number: sequence({ min: 5, max: 1 }).column() })],
  }).catalog;
  expect(() => planMigration({ before: empty, after, name: "bounds" })).toThrow(OkmError);
});

test("a counter plan creates a table, a definer, and a trigger", () => {
  const built = schema({
    tables: [
      table("docs", {
        tenantId: t.uuid().primaryKey(),
        number: sequence("doc_no", { start: 1 }).column({ scope: ["tenantId"] }),
      }),
    ],
  });
  const plan = planMigration({ before: empty, after: built.catalog, name: "counter" });
  const text = plan.steps.map((step) => step.sql).join("\n");
  expect(text).toContain("okm_ctr_doc_no");
  expect(text).toContain("security definer");
  expect(text).toContain("search_path");
  expect(text).toContain("before insert or update");
  expect(text).toContain("revoke all on table");
  expect(text).not.toContain("create sequence");
});

test("the next-function marker names the column's assign function, and the fold drops it", () => {
  const built = schema({
    tables: [
      table("issued", {
        tenantId: t.uuid().primaryKey(),
        number: sequence("docs").column({ scope: ["tenantId"] }),
      }),
    ],
  });
  const plan = planMigration({ before: empty, after: built.catalog, name: "mark" });
  const next = plan.steps.find((step) => step.sql.includes("okm_next_docs"));
  const assign = plan.steps.find((step) => step.sql.includes("okm_assign_docs_number"));
  const nextMark = seriesMarker(next?.sql ?? "");
  const assignMark = seriesMarker(assign?.sql ?? "");
  expect(nextMark?.column).toBe("number");
  expect(nextMark?.assign).toBe("okm_assign_docs_number");
  expect(nextMark?.index).toBe("okm_uq_docs_number");
  expect(nextMark?.assign).toBe(assignMark?.assign);
  expect(nextMark?.index).toBe(assignMark?.index);

  const namespace = staticNamespace("public");
  const provenance = { origin: "file" as const, name: "issued.ts" };
  const parent = { kind: "table" as const, namespace, name: "issued" };
  const folded = foldSeries(
    catalog([
      catalogTable({ namespace, name: "issued", provenance }),
      column({ parent, name: "number", dataType: "bigint", nullable: true, provenance }),
      functionObject({
        namespace,
        name: "okm_next_docs",
        language: "plpgsql",
        returns: "bigint",
        body: next?.sql ?? "",
        provenance,
      }),
      functionObject({
        namespace,
        name: "okm_assign_docs_number",
        language: "plpgsql",
        returns: "trigger",
        body: assign?.sql ?? "",
        provenance,
      }),
      catalogTable({ namespace, name: "okm_ctr_docs", provenance }),
    ]),
  );
  expect(folded.objects.some((object) => object.kind === "function")).toBe(false);
  expect(
    folded.objects.some(
      (object) => object.kind === "table" && object.identity.name === "okm_ctr_docs",
    ),
  ).toBe(false);
  const kept = folded.objects.find(
    (object) => object.kind === "column" && object.identity.name === "number",
  );
  expect(kept?.kind === "column" && kept.definition.series?.name).toBe("docs");
});

test("a when expression containing $okm$ does not close the dollar quote", () => {
  const built = schema({
    tables: [
      table("issued", {
        ready: t.boolean(),
        number: sequence("docs").column({ when: () => sql`$okm$` }),
      }),
    ],
  });
  const plan = planMigration({ before: empty, after: built.catalog, name: "tag" });
  const assign = plan.steps.find((step) => step.sql.includes("okm_assign_docs_number"));
  expect(assign?.sql).toContain("$okm$");
  expect(assign?.sql).toContain("as $okm1$");
  expect(assign?.sql.endsWith("$okm1$")).toBe(true);
});

test("ALTER SEQUENCE, a trigger, and a unique index on an existing table do not block readers", () => {
  const before = schema({
    tables: [table("issued", { id: t.integer().primaryKey(), tenantId: t.uuid() })],
  }).catalog;
  const after = schema({
    tables: [
      table("issued", {
        id: t.integer().primaryKey(),
        tenantId: t.uuid(),
        number: sequence("docs").column({ scope: ["tenantId"] }),
      }),
    ],
  }).catalog;
  const plan = planMigration({ before, after, name: "seed" });
  const trigger = plan.steps.find((step) => step.kind === "create-trigger");
  const index = plan.steps.find((step) => step.kind === "create-index");
  expect(trigger?.sql).toContain("create trigger");
  expect(index?.sql).toContain("create unique index");
  expect(trigger?.weight).toBeUndefined();
  expect(index?.weight).toBeUndefined();

  const nativeBefore = schema({
    tables: [table("docs", { number: sequence({ increment: 1 }).column() })],
  }).catalog;
  const nativeAfter = schema({
    tables: [table("docs", { number: sequence({ increment: 5 }).column() })],
  }).catalog;
  const altered = planMigration({ before: nativeBefore, after: nativeAfter, name: "alter" });
  const alteredStep = altered.steps.find((step) => step.kind === "alter-sequence");
  expect(alteredStep?.weight).toBeUndefined();
  expect(alteredStep?.lock).toBe("SHARE ROW EXCLUSIVE");
});
