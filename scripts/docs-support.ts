/**
 * Generated handbook support data.
 *
 * The floor is `POSTGRES_FLOOR`. The tested majors are `POSTGRES_VERSIONS`.
 * The version and the registry count come from the package and
 * `POSTGRES_FEATURES`. The site and the README read the files this script
 * writes. They do not retype the range.
 *
 *   bun ./scripts/docs-support.ts --write
 *   bun ./scripts/docs-support.ts --check
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { POSTGRES_VERSIONS } from "../packages/harness/src/version.js";
import { POSTGRES_FLOOR } from "../src/dialects/pg/floor.js";
import { POSTGRES_FEATURES, type Support } from "../src/tooling/capabilities/index.js";
import { repoRoot } from "./root.js";

/** How one engine provides a feature. */
export type EngineRuleKind = "min" | "range" | "any" | "bundled" | "none";

/** One major in a chip's version table. */
export type VersionRow = {
  readonly version: number;
  readonly available: boolean;
  readonly tested: boolean;
  readonly note: string;
};

/** The rule a chip and its plain-text line share. */
export type EngineRule = {
  readonly engine: string;
  readonly kind: EngineRuleKind;
  readonly label: string;
  readonly line: string;
  readonly docsOnly: boolean;
  readonly tested: readonly number[];
  readonly versions: readonly VersionRow[];
  readonly min?: number;
  readonly max?: number;
};

/** One database the handbook can mark. Postgres is the only one. */
export type EngineInfo = {
  readonly id: string;
  readonly name: string;
  readonly logo: "database";
  readonly versioned: boolean;
  readonly tested: readonly number[];
  readonly floor: number;
};

/** Numbers and sentences the handbook quotes. */
export type DocsConstants = {
  readonly version: string;
  readonly postgresFloor: number;
  readonly testedMajors: readonly number[];
  readonly testedCount: number;
  readonly featureCount: number;
  readonly floorPhrase: string;
  readonly supportPhrase: string;
  readonly tagline: string;
};

/** What a caller may pass instead of a registry entry. `max` is the range end. */
export type RuleSource = {
  readonly support: Support;
  readonly since?: string;
  readonly max?: string;
  readonly notes?: Readonly<Record<string, string>>;
};

/**
 * Majors marked tested on this branch.
 *
 * The release step replaces this list with the full matrix. Until then the
 * file says CI ran on 18.
 */
export const TESTED_MATRIX_MAJORS = [18] as const;

/** Sentence stored in `tested-matrix` until the release step fills the matrix. */
export const TESTED_MATRIX_NOTE = "CI ran on 18, full matrix at release";

const GENERATED_HEADER = "/**\n * Generated by `scripts/docs-support.ts`. Do not edit.\n */\n";

const CONSTANTS_FILE = "site/lib/generated/docs-constants.ts";
const MATRIX_FILE = "site/lib/generated/tested-matrix.ts";
const RULES_FILE = "site/lib/generated/feature-rules.ts";

/** Handbook files that must quote {@link docsConstants} `supportPhrase`. */
const PHRASE_FILES = [
  "README.md",
  "package.json",
  "site/content/docs/index.mdx",
  "site/content/docs/schema/the-schema.mdx",
] as const;

/**
 * Support numbers for the current tree.
 *
 * @param root - Repository root
 * @returns Floor, tested majors, version, registry count, and the sentences
 */
export function docsConstants(root: string = repoRoot()): DocsConstants {
  const majors = testedMajors();
  const floor = majors[0];
  if (floor === undefined || floor !== POSTGRES_FLOOR) {
    throw new Error("docs-support: the tested list does not start at POSTGRES_FLOOR");
  }
  const newest = majors[majors.length - 1];
  if (newest === undefined) throw new Error("docs-support: the tested list is empty");
  const supportPhrase = `PostgreSQL ${String(floor)} and later; tested on ${String(floor)} to ${String(newest)}`;
  return {
    version: packageVersion(root),
    postgresFloor: floor,
    testedMajors: majors,
    testedCount: majors.length,
    featureCount: Object.keys(POSTGRES_FEATURES).length,
    floorPhrase: `PostgreSQL ${String(floor)} and later`,
    supportPhrase,
    tagline: `okmodel is a TypeScript ORM for ${supportPhrase} with no runtime dependencies.`,
  };
}

/**
 * The engine map. Postgres only. Another engine is another entry here, not a
 * second empty table.
 *
 * @returns The map keyed by id
 */
export function engines(): Readonly<Record<string, EngineInfo>> {
  const majors = testedMajors();
  const floor = majors[0];
  if (floor === undefined) throw new Error("docs-support: the tested list is empty");
  return {
    postgres: {
      id: "postgres",
      name: "PostgreSQL",
      logo: "database",
      versioned: true,
      tested: majors,
      floor,
    },
  };
}

/**
 * Rule for one registry entry on one engine.
 *
 * `refused` is `none`. `emulated` is `bundled`. A `since` and a `max` are
 * `range`. A `since` alone is `min`. Anything else native is `any`.
 *
 * @param engine - Engine the chip names
 * @param source - Registry entry, or a fixture that also sets `max`
 * @param tested - Majors marked tested, from `tested-matrix`
 * @param docsOnly - True when the heading has no registry proof
 * @returns The chip rule and the plain line
 */
export function engineRule(
  engine: EngineInfo,
  source: RuleSource,
  tested: readonly number[] = TESTED_MATRIX_MAJORS,
  docsOnly = false,
): EngineRule {
  const notes = source.notes ?? {};
  const since = majorOf(source.since);
  const max = majorOf(source.max);
  const kind = ruleKind(source.support, since, max);
  const min = kind === "min" || kind === "range" ? since : undefined;
  const boundedMax = kind === "range" ? max : undefined;
  const label = ruleLabel(kind, min, boundedMax);
  const versions = versionRows(engine.tested, kind, min, boundedMax, tested, notes);
  const marked = versions.flatMap((row) => (row.tested ? [row.version] : []));
  return {
    engine: engine.id,
    kind,
    label,
    line: ruleLine(engine.name, label, engine, source, docsOnly, kind),
    docsOnly,
    tested: marked,
    versions,
    ...(min === undefined ? {} : { min }),
    ...(boundedMax === undefined ? {} : { max: boundedMax }),
  };
}

/**
 * Docs-only chip for a heading that names an engine and no registry key.
 *
 * @param engine - Engine the heading named
 * @param tested - Majors marked tested
 * @returns A floor chip marked docs only, no proof
 */
export function docsOnlyRule(
  engine: EngineInfo,
  tested: readonly number[] = TESTED_MATRIX_MAJORS,
): EngineRule {
  return engineRule(engine, { support: "native", since: String(engine.floor) }, tested, true);
}

/**
 * One rule per registry key, in registry order.
 *
 * @returns The map the generated file stores
 */
export function featureRules(): Readonly<Record<string, EngineRule>> {
  const engine = engines().postgres;
  if (engine === undefined) throw new Error("docs-support: postgres is missing from ENGINES");
  const rules: Record<string, EngineRule> = {};
  for (const [key, entry] of Object.entries(POSTGRES_FEATURES)) {
    rules[key] = engineRule(engine, entry);
  }
  return rules;
}

/**
 * README constants block, without the marker comments.
 *
 * @param constants - {@link docsConstants}
 * @returns One paragraph
 */
export function readmeConstantsBlock(constants: DocsConstants = docsConstants()): string {
  return `okmodel ${constants.version}. ${constants.supportPhrase}. ${String(constants.testedCount)} tested majors. ${String(constants.featureCount)} registry features.`;
}

/**
 * README support table, without the marker comments.
 *
 * The engine cell is the chip's name. The minimum is the floor. Tested is
 * the suite range. The matrix note says what CI has marked.
 *
 * @returns Markdown table plus the matrix note
 */
export function readmeSupportTable(): string {
  const engine = engines().postgres;
  if (engine === undefined) throw new Error("docs-support: postgres is missing from ENGINES");
  const first = engine.tested[0];
  const last = engine.tested[engine.tested.length - 1];
  const range = `${String(first)} to ${String(last)}`;
  const table = alignedTable(
    ["Engine", "Minimum", "Tested"],
    [[engine.name, `${String(engine.floor)}+`, range]],
  );
  return `${table}\n\n${TESTED_MATRIX_NOTE}`;
}

/**
 * Markdown table with padded columns, the shape oxfmt keeps.
 *
 * @param headers - Column titles
 * @param rows - Body cells, one array per row
 * @returns The table, no trailing newline
 */
function alignedTable(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const widths = headers.map((header, index) => {
    let width = header.length;
    for (const row of rows) {
      const cell = row[index] ?? "";
      if (cell.length > width) width = cell.length;
    }
    return width;
  });
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((cell, index) => cell.padEnd(widths[index] ?? cell.length)).join(" | ")} |`;
  const rule = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;
  return [line(headers), rule, ...rows.map((row) => line(row))].join("\n");
}

/**
 * Problems when a generated file differs from the registry, or a quoted
 * sentence differs from {@link docsConstants}.
 *
 * @param root - Repository root
 * @returns Problem lines. Empty when the files match
 */
export function docsSupportProblems(root: string = repoRoot()): readonly string[] {
  const problems: string[] = [];
  const expected = new Map<string, string>([
    [CONSTANTS_FILE, renderConstantsModule(docsConstants(root))],
    [MATRIX_FILE, renderMatrixModule()],
    [RULES_FILE, renderRulesModule(featureRules(), docsOnlyRule(requiredPostgres()))],
  ]);
  for (const [rel, text] of expected) {
    const full = join(root, rel);
    let actual = "";
    try {
      actual = readFileSync(full, "utf8");
    } catch {
      problems.push(`docs-support: missing ${rel}. Run bun ./scripts/docs-support.ts --write`);
      continue;
    }
    if (actual !== text) {
      problems.push(`docs-support: ${rel} is stale. Run bun ./scripts/docs-support.ts --write`);
    }
  }
  const constants = docsConstants(root);
  for (const rel of PHRASE_FILES) {
    const text = readFileSync(join(root, rel), "utf8");
    if (!text.includes(constants.supportPhrase)) {
      problems.push(`docs-support: ${rel} does not quote ${constants.supportPhrase}`);
    }
    if (rel === "package.json" && !text.includes(constants.tagline)) {
      problems.push("docs-support: package.json description is not the generated tagline");
    }
  }
  return problems;
}

/**
 * Write the three generated modules.
 *
 * @param root - Repository root
 */
export function writeDocsSupport(root: string = repoRoot()): void {
  const postgres = requiredPostgres();
  writeFileSync(join(root, CONSTANTS_FILE), renderConstantsModule(docsConstants(root)));
  writeFileSync(join(root, MATRIX_FILE), renderMatrixModule());
  writeFileSync(join(root, RULES_FILE), renderRulesModule(featureRules(), docsOnlyRule(postgres)));
}

/**
 * Registry keys named by a handbook page, and keys a page names that are not
 * in the registry.
 *
 * @param files - Handbook path and full text. Fenced code is ignored.
 * @param keys - Registry keys
 * @returns Mapped keys and unknown references
 */
export function featureReferences(
  files: readonly { readonly path: string; readonly text: string }[],
  keys: ReadonlySet<string>,
): {
  readonly mapped: ReadonlySet<string>;
  readonly unknown: readonly { readonly path: string; readonly key: string }[];
} {
  const mapped = new Set<string>();
  const unknown: { path: string; key: string }[] = [];
  for (const file of files) {
    for (const key of featureKeysIn(file.text)) {
      if (keys.has(key)) mapped.add(key);
      else unknown.push({ path: file.path, key });
    }
  }
  return { mapped, unknown };
}

function requiredPostgres(): EngineInfo {
  const engine = engines().postgres;
  if (engine === undefined) throw new Error("docs-support: postgres is missing from ENGINES");
  return engine;
}

function testedMajors(): readonly number[] {
  return POSTGRES_VERSIONS.map((version) => Number(version));
}

function packageVersion(root: string): string {
  const parsed: unknown = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  if (typeof parsed !== "object" || parsed === null || !("version" in parsed)) {
    throw new Error("docs-support: package.json has no version");
  }
  const version = parsed.version;
  if (typeof version !== "string" || version.length === 0) {
    throw new Error("docs-support: package.json version is not a string");
  }
  return version;
}

function majorOf(value: string | undefined): number | undefined {
  if (value === undefined || value.length === 0) return undefined;
  const major = Number(value);
  if (!Number.isInteger(major)) return undefined;
  return major;
}

function ruleKind(
  support: Support,
  since: number | undefined,
  max: number | undefined,
): EngineRuleKind {
  if (support === "refused") return "none";
  if (support === "emulated") return "bundled";
  if (since !== undefined && max !== undefined) return "range";
  if (since !== undefined) return "min";
  return "any";
}

function ruleLabel(kind: EngineRuleKind, min: number | undefined, max: number | undefined): string {
  if (kind === "none") return "none";
  if (kind === "bundled") return "bundled";
  if (kind === "any") return "any";
  if (kind === "range" && min !== undefined && max !== undefined)
    return `${String(min)}–${String(max)}`;
  if (min !== undefined) return `${String(min)}+`;
  return "any";
}

function ruleLine(
  engineName: string,
  label: string,
  engine: EngineInfo,
  source: RuleSource,
  docsOnly: boolean,
  kind: EngineRuleKind,
): string {
  if (kind === "none") return `${engineName} none`;
  const first = engine.tested[0];
  const last = engine.tested[engine.tested.length - 1];
  const parts = [`${engineName} ${label}`, `tested ${String(first)} to ${String(last)}`];
  if (docsOnly) parts.push("docs only, no proof");
  else if (source.support === "native" && source.since !== undefined && source.since.length > 0) {
    parts.push(`native since ${source.since}`);
  }
  return parts.join(", ");
}

function versionRows(
  majors: readonly number[],
  kind: EngineRuleKind,
  min: number | undefined,
  max: number | undefined,
  tested: readonly number[],
  notes: Readonly<Record<string, string>>,
): readonly VersionRow[] {
  const testedSet = new Set(tested);
  return majors.map((version) => {
    const available = isAvailable(kind, version, min, max);
    return {
      version,
      available,
      tested: available && testedSet.has(version),
      note: notes[String(version)] ?? "",
    };
  });
}

function isAvailable(
  kind: EngineRuleKind,
  version: number,
  min: number | undefined,
  max: number | undefined,
): boolean {
  if (kind === "none") return false;
  if (kind === "any" || kind === "bundled") return true;
  if (min === undefined) return false;
  if (version < min) return false;
  if (kind === "range" && max !== undefined && version > max) return false;
  return true;
}

function featureKeysIn(text: string): readonly string[] {
  const keys: string[] = [];
  const body = outsideFences(text);
  for (const match of body.matchAll(/^feature:\s*"?([A-Za-z0-9_.-]+)"?\s*$/gm)) {
    const key = match[1];
    if (key !== undefined) keys.push(key);
  }
  for (const match of body.matchAll(/[{[][^}\n]*\bfeature="([^"]+)"[^}\n]*[}\]]/g)) {
    const key = match[1];
    if (key !== undefined) keys.push(key);
  }
  return keys;
}

function outsideFences(text: string): string {
  return text.replace(/```[\s\S]*?```/g, (block) => block.replace(/[^\n]/g, ""));
}

function renderConstantsModule(constants: DocsConstants): string {
  const engine = requiredPostgres();
  return `${GENERATED_HEADER}
/** Package version the docs quote. */
export const DOCS_VERSION = ${JSON.stringify(constants.version)};

/** Oldest PostgreSQL major okmodel accepts. */
export const POSTGRES_FLOOR = ${String(constants.postgresFloor)};

/** Majors the suite runs, oldest first. */
export const TESTED_MAJORS = ${JSON.stringify(constants.testedMajors)} as const;

/** How many majors the suite runs. */
export const TESTED_COUNT = ${String(constants.testedCount)};

/** Keys in \`POSTGRES_FEATURES\`. */
export const FEATURE_COUNT = ${String(constants.featureCount)};

/** Floor claim, without the tested range. */
export const FLOOR_PHRASE = ${JSON.stringify(constants.floorPhrase)};

/** Floor and tested range. Handbook pages quote this sentence. */
export const SUPPORT_PHRASE = ${JSON.stringify(constants.supportPhrase)};

/** Package description and the README positioning sentence. */
export const TAGLINE = ${JSON.stringify(constants.tagline)};

/**
 * Engines the handbook marks.
 *
 * \`logo: "database"\` is the neutral glyph. The Slonik elephant is a
 * registered mark and is not redrawn here.
 */
export const ENGINES = ${emit(engineMap(engine), 0)} as const;
`;
}

function engineMap(engine: EngineInfo): Record<string, EngineInfo> {
  return { [engine.id]: engine };
}

function renderMatrixModule(): string {
  return `${GENERATED_HEADER}
/**
 * Majors this branch marks as tested.
 *
 * The release step fills the full matrix. Until then the note stands.
 */
export const TESTED_MATRIX_NOTE = ${JSON.stringify(TESTED_MATRIX_NOTE)};

/** Majors with a tested mark. */
export const TESTED_MATRIX = ${JSON.stringify([...TESTED_MATRIX_MAJORS])} as const;
`;
}

function renderRulesModule(
  rules: Readonly<Record<string, EngineRule>>,
  docsOnly: EngineRule,
): string {
  return `${GENERATED_HEADER}
import type { EngineRule } from "../feature-model";

/** One rule per \`POSTGRES_FEATURES\` key, in registry order. */
export const FEATURE_RULES: Readonly<Record<string, EngineRule>> = ${emit(rules, 0)};

/** Chip for a heading that names Postgres and no registry key. */
export const DOCS_ONLY_POSTGRES: EngineRule = ${emit(docsOnly, 0)};
`;
}

function emit(value: unknown, indent: number): string {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (value.every((item) => typeof item === "number" || typeof item === "string")) {
      return `[${value.map((item) => emit(item, indent)).join(", ")}]`;
    }
    const pad = "  ".repeat(indent);
    const inner = value.map((item) => `${pad}  ${emit(item, indent + 1)}`).join(",\n");
    return `[\n${inner},\n${pad}]`;
  }
  if (typeof value === "object" && value !== null) {
    const pad = "  ".repeat(indent);
    const inner = Object.entries(value)
      .map(([key, item]) => {
        const name = /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : JSON.stringify(key);
        return `${pad}  ${name}: ${emit(item, indent + 1)}`;
      })
      .join(",\n");
    return `{\n${inner},\n${pad}}`;
  }
  throw new Error("docs-support: cannot emit this value");
}

if (import.meta.main) {
  const write = process.argv.includes("--write");
  const root = repoRoot();
  if (write) {
    writeDocsSupport(root);
    console.log("docs-support: wrote generated modules");
  }
  const problems = docsSupportProblems(root);
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  if (!write) console.log("docs-support: generated modules match");
}
