/**
 * Cloudflare Workers + Neon example.
 *
 * Always checks that the Worker bundles under Cloudflare's documented size
 * ceiling with `nodejs_compat`. The live read/write test needs Neon
 * credentials and is intended for Nightly (`OKM_EXAMPLES_NIGHTLY=1`); without
 * credentials or the nightly flag it skips.
 */

import { expect, test } from "bun:test";
import { spawn } from "bun";
import { mkdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";

import { neon } from "@neondatabase/serverless";
import { Miniflare } from "miniflare";

import { linkOkmodel } from "../shared/support.js";

const exampleDir = join(import.meta.dir);
const outDir = join(exampleDir, ".wrangler-bundle");

/** Cloudflare Workers free plan script size limit (compressed), as documented. */
const CF_FREE_GZIP_LIMIT = 3 * 1024 * 1024;

async function bundleWorker(): Promise<{ script: string; gzipKiB: number }> {
  linkOkmodel(exampleDir);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const build = spawn({
    cmd: ["bunx", "wrangler", "deploy", "--dry-run", `--outdir=${outDir}`],
    cwd: exampleDir,
    stdout: "pipe",
    stderr: "pipe",
  });
  const code = await build.exited;
  const log = `${await new Response(build.stdout).text()}\n${await new Response(build.stderr).text()}`;
  if (code !== 0) throw new Error(`wrangler dry-run failed:\n${log}`);
  const match = log.match(/Total Upload:\s*([\d.]+)\s*KiB\s*\/\s*gzip:\s*([\d.]+)\s*KiB/);
  if (match === null) throw new Error(`wrangler size line missing:\n${log}`);
  const scriptPath = join(outDir, "worker.js");
  return { script: readFileSync(scriptPath, "utf8"), gzipKiB: Number(match[2]) };
}

test("workers-neon bundle stays under the Cloudflare size limit", async () => {
  const { script, gzipKiB } = await bundleWorker();
  expect(gzipKiB * 1024).toBeLessThan(CF_FREE_GZIP_LIMIT);
  expect(script.length).toBeGreaterThan(10_000);
  expect(readFileSync(join(exampleDir, "wrangler.toml"), "utf8")).toContain("nodejs_compat");
});

test("workers-neon rejects an unknown NEON_MODE before opening a client", async () => {
  const { script } = await bundleWorker();
  const mf = new Miniflare({
    modules: true,
    script,
    compatibilityDate: "2025-10-01",
    compatibilityFlags: ["nodejs_compat"],
    bindings: { DATABASE_URL: "postgres://unused.invalid/db", NEON_MODE: "ws" },
  });
  try {
    const response = await mf.dispatchFetch("http://localhost/health");
    expect(response.status).toBe(500);
    expect(await response.text()).toContain('NEON_MODE must be "websocket" or "http"');
  } finally {
    await mf.dispose();
  }
}, 60_000);

const neonUrl = process.env.NEON_URL;
const nightly = process.env.OKM_EXAMPLES_NIGHTLY === "1";
const live = nightly && typeof neonUrl === "string" && neonUrl.length > 0 ? test : test.skip;

live("workers-neon live read/write in websocket and http modes", async () => {
  const url = neonUrl!;
  const sql = neon(url);
  await sql`DROP TABLE IF EXISTS example_notes`;
  await sql`
    CREATE TABLE example_notes (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title text NOT NULL
    )
  `;

  const { script } = await bundleWorker();

  async function exercise(mode: "websocket" | "http"): Promise<void> {
    const mf = new Miniflare({
      modules: true,
      script,
      compatibilityDate: "2025-10-01",
      compatibilityFlags: ["nodejs_compat"],
      bindings: { DATABASE_URL: url, NEON_MODE: mode },
    });
    try {
      const written = await mf.dispatchFetch("http://localhost/notes", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ title: `workers-${mode}` }),
      });
      expect(written.status).toBe(201);
      const listed = await mf.dispatchFetch("http://localhost/notes");
      expect(listed.status).toBe(200);
      const rows = (await listed.json()) as Array<{ title: string }>;
      expect(rows.some((row) => row.title === `workers-${mode}`)).toBe(true);
    } finally {
      await mf.dispose();
    }
  }

  await exercise("http");
  await exercise("websocket");
}, 120_000);
